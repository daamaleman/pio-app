/** Miskitu uses a reviewable draft until the language team supplies approved copy. */
export function t(key: keyof typeof copy, language: AppLanguage): string {
  const translation = copy[key];
  if (language === 'miq') return translation?.miq ?? toMiskituDraft(translation?.es ?? String(key));
  return translation?.[language] ?? translation?.es ?? String(key);
}

/** Fallback documented by the API: when a locale is not supplied, show Spanish. */
export function localizedText(copy: Partial<Record<AppLanguage, string>>, language: AppLanguage): string {
  if (language === 'miq') return copy.miq ?? toMiskituDraft(copy.es ?? '');
  return copy[language] ?? copy.es ?? '';
}

